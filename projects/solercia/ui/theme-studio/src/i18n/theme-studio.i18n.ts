/** Prefijo de todas las claves de la pantalla en el motor de traducción del host. */
export const THEME_STUDIO_I18N_PREFIX = 'sol.themeStudio.';

function lookup(dictionary: ThemeStudioDictionary, path: string): string | undefined {
  let node: string | ThemeStudioDictionary | undefined = dictionary;
  for (const segment of path.split('.')) {
    if (node === undefined || typeof node === 'string') return undefined;
    node = node[segment];
  }
  return typeof node === 'string' ? node : undefined;
}

function interpolate(template: string, params?: Record<string, unknown>): string {
  if (!params) return template;
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

